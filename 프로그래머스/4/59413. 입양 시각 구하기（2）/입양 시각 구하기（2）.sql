SELECT LIST.HOUR, NVL(FILTER_COUNT.COUNT, 0) AS "COUNT"
FROM (SELECT LEVEL - 1 AS HOUR
FROM DUAL
CONNECT BY LEVEL <= 24) LIST,
(SELECT TO_NUMBER(TO_CHAR(DATETIME, 'HH24')) AS "HOUR", COUNT(*) AS "COUNT"
FROM ANIMAL_OUTS
GROUP BY TO_NUMBER(TO_CHAR(DATETIME, 'HH24'))
ORDER BY TO_NUMBER(TO_CHAR(DATETIME, 'HH24'))) FILTER_COUNT
WHERE LIST.HOUR = FILTER_COUNT.HOUR(+)
ORDER BY LIST.HOUR