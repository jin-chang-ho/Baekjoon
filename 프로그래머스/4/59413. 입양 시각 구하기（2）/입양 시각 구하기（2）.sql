SELECT HOUR_FILTER.HOUR, NVL(ANIMAL_FILTER.COUNT, 0) AS "COUNT"
FROM (
    SELECT LEVEL - 1 AS "HOUR"
    FROM DUAL
    CONNECT BY LEVEL <= 24
) HOUR_FILTER,
(
    SELECT TO_CHAR(DATETIME, 'HH24') AS "HOUR", COUNT(*) AS "COUNT" 
    FROM ANIMAL_OUTS
    GROUP BY TO_CHAR(DATETIME, 'HH24')
) ANIMAL_FILTER
WHERE HOUR_FILTER.HOUR = ANIMAL_FILTER.HOUR(+)
ORDER BY HOUR_FILTER.HOUR