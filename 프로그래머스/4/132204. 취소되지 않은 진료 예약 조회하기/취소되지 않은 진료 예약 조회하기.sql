SELECT APPOINTMENT.APNT_NO, PATIENT.PT_NAME, APPOINTMENT.PT_NO, APPOINTMENT.MCDP_CD, DOCTOR.DR_NAME, APPOINTMENT.APNT_YMD
FROM APPOINTMENT, PATIENT, DOCTOR
WHERE APPOINTMENT.PT_NO = PATIENT.PT_NO
AND APPOINTMENT.MDDR_ID = DOCTOR.DR_ID
AND NVL(APPOINTMENT.APNT_CNCL_YN, 'N') = 'N'
AND APPOINTMENT.MCDP_CD = 'CS'
AND TO_CHAR(APPOINTMENT.APNT_YMD, 'YYYYMMDD') = '20220413'
ORDER BY APPOINTMENT.APNT_YMD