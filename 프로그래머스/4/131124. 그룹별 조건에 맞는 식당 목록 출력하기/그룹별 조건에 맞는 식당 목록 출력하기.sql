SELECT MEMBER_PROFILE.MEMBER_NAME, REST_REVIEW.REVIEW_TEXT, TO_CHAR(REST_REVIEW.REVIEW_DATE, 'YYYY-MM-DD') AS "REVIEW_DATE"
FROM MEMBER_PROFILE, (
    SELECT MEMBER_ID,
            RANK() OVER (ORDER BY COUNT(*) DESC) RK
    FROM REST_REVIEW
    GROUP BY MEMBER_ID
) FILTER, REST_REVIEW
WHERE RK = '1'
AND MEMBER_PROFILE.MEMBER_ID = FILTER.MEMBER_ID
AND FILTER.MEMBER_ID = REST_REVIEW.MEMBER_ID
ORDER BY REST_REVIEW.REVIEW_DATE, REST_REVIEW.REVIEW_TEXT