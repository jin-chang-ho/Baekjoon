SELECT MEMBER_PROFILE.MEMBER_NAME, REST_REVIEW.REVIEW_TEXT, TO_CHAR(REST_REVIEW.REVIEW_DATE, 'YYYY-MM-DD') AS REVIEW_DATE
FROM MEMBER_PROFILE, REST_REVIEW
WHERE MEMBER_PROFILE.MEMBER_ID = REST_REVIEW.MEMBER_ID
AND MEMBER_PROFILE.MEMBER_ID IN (
    SELECT MEMBER_ID
    FROM REST_REVIEW
    GROUP BY MEMBER_ID
    HAVING COUNT(*) = (SELECT MAX(COUNT(*))
    FROM REST_REVIEW
    GROUP BY MEMBER_ID) 
)
ORDER BY REST_REVIEW.REVIEW_DATE, REST_REVIEW.REVIEW_TEXT