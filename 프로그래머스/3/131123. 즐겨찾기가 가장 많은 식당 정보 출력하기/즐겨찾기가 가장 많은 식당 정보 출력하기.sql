-- 목표 : 음식종류별로 즐겨찾기수가 가장 많은 식당의 음식 종류, ID, 식당 이름, 즐겨찾기수를 조회
-- 풀이
-- 1. REST_INFO 테이블에서 FOOD_TYPE 별 가장 많은 즐겨찾기 수를 필터링한다.
-- 2. 위 정보와 REST_INFO 를 매핑해 해당 식당을 찾고, 문제에서 요구한 답을 적절한 형식으로 출력한다.

SELECT REST_INFO.FOOD_TYPE, REST_INFO.REST_ID, REST_INFO.REST_NAME, REST_INFO.FAVORITES
FROM REST_INFO,
(SELECT FOOD_TYPE, MAX(IFNULL(FAVORITES, 0)) AS FOOD_FAVORITE
FROM REST_INFO
GROUP BY FOOD_TYPE) REST_INFO_FIRTER
WHERE REST_INFO.FOOD_TYPE = REST_INFO_FIRTER.FOOD_TYPE
AND REST_INFO.FAVORITES = REST_INFO_FIRTER.FOOD_FAVORITE
ORDER BY REST_INFO.FOOD_TYPE DESC