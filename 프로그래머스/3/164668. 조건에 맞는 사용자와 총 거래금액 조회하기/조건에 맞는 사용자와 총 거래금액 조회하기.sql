SELECT USED_GOODS_USER.USER_ID, USED_GOODS_USER.NICKNAME, USED_SUM_PRICE.SUMPRICE AS "TOTAL_SALES"
FROM USED_GOODS_USER,
( 
    SELECT WRITER_ID, SUM(PRICE) AS "SUMPRICE"
    FROM USED_GOODS_BOARD
    WHERE USED_GOODS_BOARD.STATUS = 'DONE'
    GROUP BY WRITER_ID
    HAVING SUM(PRICE) >= 700000
) USED_SUM_PRICE
WHERE USED_GOODS_USER.USER_ID = USED_SUM_PRICE.WRITER_ID
ORDER BY USED_SUM_PRICE.SUMPRICE